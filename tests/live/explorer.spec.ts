import {test,expect} from '@playwright/test';
test('real map, search, nearby places and walking/cycling routes',async({page})=>{
 const errors:string[]=[];
 page.on('pageerror',e=>errors.push(e.message));
 const tiles:string[]=[];
 page.on('response',r=>{if(r.ok()&&r.url().includes('tiles.openfreemap.org'))tiles.push(r.url());});
 await page.goto('/');
 await expect(page.getByRole('button',{name:/Parc du Près-la-Rose/})).toBeVisible();
 await page.getByRole('button',{name:/Parc du Près-la-Rose/}).click();
 await page.getByRole('button',{name:'Enregistrer ce lieu',exact:true}).click();
 await page.reload();
 await page.getByRole('region',{name:'Lieux enregistrés'}).getByRole('button',{name:'Parc du Près-la-Rose Nature',exact:true}).click();
 await expect(page.getByRole('region',{name:'Lieux à proximité'}).getByRole('button',{name:/Gare de Montbéliard/})).toBeVisible();
 await page.getByLabel('Lieu de départ').selectOption('gare');
 const summary=page.getByRole('region',{name:'Itinéraire'}).locator('strong');
 await expect(summary).toContainText(/\d+ m · \d+ min/);
 await expect(page.getByRole('region',{name:'Itinéraire'}).locator('ol li')).not.toHaveCount(0);
 await expect(page.getByText('Accessibilité du trajet non vérifiée.',{exact:false})).toBeVisible();
 const cycleResponse=page.waitForResponse(r=>r.url().includes('/api/routes?')&&r.url().includes('mode=bicycle'));
 await page.getByLabel('Mode de déplacement').selectOption('bicycle');
 expect((await cycleResponse).ok()).toBe(true);
 await expect(summary).toContainText(/\d+ m · \d+ min/);
 await page.getByRole('button',{name:'Fermer les détails'}).click();
 await page.getByLabel('Rechercher dans').selectOption('address');
 await page.getByRole('textbox',{name:'Rechercher un lieu'}).fill('gare Montbéliard');
 await expect(page.locator('.place-list .place').first()).toBeVisible();
 await expect.poll(()=>tiles.length).toBeGreaterThan(2);
 await expect.poll(()=>page.locator('.map').evaluate(e=>e.clientHeight)).toBeGreaterThan(300);
 await expect.poll(()=>page.locator('.maplibregl-canvas').evaluate(e=>e.clientHeight)).toBeGreaterThan(300);
 await expect.poll(()=>page.locator('.maplibregl-canvas').evaluate(e=>e.clientWidth)).toBeGreaterThan(200);
 await expect(page.locator('.map-error')).toHaveCount(0);
 await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 expect(errors).toEqual([]);
 await page.screenshot({path:`test-results/live-${test.info().project.name}.png`,fullPage:true});
});
